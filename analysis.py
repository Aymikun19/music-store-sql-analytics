"""Run every query in sql/, save results, draw charts and build REPORT.md.

Usage:  python analysis.py
"""
from __future__ import annotations

import sqlite3
from pathlib import Path
from urllib.request import urlretrieve

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).parent
DB = ROOT / "data" / "chinook.sqlite"
URL = "https://raw.githubusercontent.com/lerocha/chinook-database/master/ChinookDatabase/DataSources/Chinook_Sqlite.sqlite"
plt.rcParams.update({"figure.dpi": 130, "axes.spines.top": False, "axes.spines.right": False})


def connect() -> sqlite3.Connection:
    if not DB.exists():
        DB.parent.mkdir(exist_ok=True)
        urlretrieve(URL, DB)
    return sqlite3.connect(DB)


def run_all(con: sqlite3.Connection) -> dict[str, tuple[str, pd.DataFrame]]:
    out = {}
    for f in sorted((ROOT / "sql").glob("*.sql")):
        sql = f.read_text()
        question = sql.splitlines()[0].lstrip("- ").strip()
        df = pd.read_sql_query(sql, con)
        df.to_csv(ROOT / "results" / f"{f.stem}.csv", index=False)
        out[f.stem] = (question, df)
    return out


def charts(r: dict[str, tuple[str, pd.DataFrame]]) -> None:
    figs = ROOT / "figures"
    m = r["01_monthly_revenue"][1]
    fig, ax = plt.subplots(figsize=(9, 3.5))
    ax.bar(m["month"], m["revenue"], color="#cbd5e1", label="Monthly revenue")
    ax.plot(m["month"], m["revenue_3mo_avg"], color="#0f766e", lw=2, label="3-month average")
    ax.set_xticks(m["month"][::6])
    ax.set_ylabel("USD")
    ax.legend(frameon=False)
    ax.set_title("Monthly revenue")
    fig.tight_layout()
    fig.savefig(figs / "monthly_revenue.png")

    g = r["03_genre_share"][1].head(10)
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.barh(g["genre"][::-1], g["revenue"][::-1], color="#7c3aed")
    ax2 = ax.twiny()
    ax2.plot(g["cumulative_pct"][::-1], g["genre"][::-1], "o-", color="#f59e0b")
    ax2.set_xlim(0, 105)
    ax2.set_xlabel("Cumulative % of revenue", color="#b45309")
    ax.set_xlabel("Revenue (USD)")
    ax.set_title("Top 10 genres: revenue and Pareto curve", pad=30)
    fig.tight_layout()
    fig.savefig(figs / "genre_pareto.png")

    seg = r["04_rfm_segments"][1].groupby("segment").agg(customers=("customer", "count"), revenue=("monetary", "sum")).sort_values("revenue")
    fig, ax = plt.subplots(figsize=(7, 3.5))
    ax.barh(seg.index, seg["revenue"], color="#0284c7")
    for i, (c, v) in enumerate(zip(seg["customers"], seg["revenue"])):
        ax.text(v, i, f"  {c} customers", va="center", fontsize=9)
    ax.set_xlabel("Lifetime revenue (USD)")
    ax.set_title("Revenue by RFM segment")
    fig.tight_layout()
    fig.savefig(figs / "rfm_segments.png")

    c = r["05_cohort_retention"][1].pivot(index="cohort", columns="years_since_first", values="retention_pct")
    fig, ax = plt.subplots(figsize=(6, 3))
    im = ax.imshow(c.values, cmap="Greens", vmin=0, vmax=100)
    ax.set_xticks(range(len(c.columns)), [f"+{y}y" for y in c.columns])
    ax.set_yticks(range(len(c.index)), c.index)
    for (i, j), v in pd.DataFrame(c.values).stack().items():
        ax.text(j, i, f"{v:.0f}%", ha="center", va="center", fontsize=8)
    ax.set_title("Cohort retention by first-purchase year")
    fig.colorbar(im, ax=ax, shrink=0.8)
    fig.tight_layout()
    fig.savefig(figs / "cohort_retention.png")
    plt.close("all")


def report(r: dict[str, tuple[str, pd.DataFrame]]) -> None:
    parts = ["# Analysis report\n\n*Generated by `python analysis.py`. Every table below is the output of the matching file in `sql/`.*\n"]
    imgs = {"01_monthly_revenue": "monthly_revenue", "03_genre_share": "genre_pareto", "04_rfm_segments": "rfm_segments", "05_cohort_retention": "cohort_retention"}
    for key, (q, df) in r.items():
        parts.append(f"\n## {q}\n\nQuery: [`sql/{key}.sql`](sql/{key}.sql)\n")
        if key in imgs:
            parts.append(f"\n![](figures/{imgs[key]}.png)\n")
        shown = (df if len(df) <= 15 else df.head(15)).astype(object).where(lambda d: d.notna(), "–")
        parts.append("\n" + shown.to_markdown(index=False) + ("\n\n*(first 15 rows)*" if len(df) > 15 else "") + "\n")
    (ROOT / "REPORT.md").write_text("".join(parts))


if __name__ == "__main__":
    con = connect()
    results = run_all(con)
    charts(results)
    report(results)
    for k, (q, df) in results.items():
        print(f"{k}: {len(df)} rows")
